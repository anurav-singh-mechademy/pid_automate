"""Build descgen/vocab_cfihos.py from the CFIHOS Reference Data Library v2.0 (IOGP JIP36, issued 2024-11-01, public
linked data at posccaesar.org; local copy external/cfihos/: cfihos_rdl_v2.0.nt + classes.json with each class's
label, definition and subClassOf parent).
    .venv/bin/python -m descgen.build_vocab
Every CFIHOS equipment class takes the kind of its nearest ancestor (or itself) listed in BRANCH_KIND, or of its own
head noun when that noun is already a descgen kind noun. Head nouns that are new to rules.KIND_OF_NOUN are written
out as extra kind nouns (existing entries always win; nouns shorter than 5 letters are left out because they would
be taken whole by the word splitter inside longer words; words descgen already uses for something else - vocabulary,
consumer, note and title words such as CYLINDER or FLARE - and generic heads such as CLASS or SYSTEM are skipped)."""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# CFIHOS class label -> descgen equipment kind (rules.MACHINE_RULES keys)
BRANCH_KIND = {"pump": "pump", "compressor": "compressor", "vessel": "vessel", "process column": "vessel",
               "tank": "tank", "sump": "tank", "heat exchanger": "exchanger", "fired heat transfer equipment class": "heater",
               "electric heater": "heater", "turbine": "turbine", "gas turbine": "turbine", "steam turbine": "turbine",
               "electric motor": "motor", "filter": "filter", "strainer": "filter", "blower": "compressor", "fan": "compressor"}


# heads that name no equipment ('mechanical equipment class', '... system') and kinds outside process equipment
GENERIC = {"CLASS", "SYSTEM", "EQUIPMENT", "UNIT", "PACKAGE", "SKID", "GRILLE"}
KEEP_KINDS = {"pump", "compressor", "turbine", "motor", "vessel", "tank", "exchanger", "heater", "filter", "accessory"}


def main():
    from descgen import rules as R
    C = {c["uri"]: c for c in json.load(open(ROOT / "external/cfihos/classes.json")) if "label" in c}
    known = {k.lower(): v for k, v in R.HAND_KIND_OF_NOUN.items()}

    def kind(u):
        seen = set()
        while u in C and u not in seen:
            seen.add(u)
            lab = C[u]["label"].lower()
            if lab in BRANCH_KIND:
                return BRANCH_KIND[lab], lab
            head = re.sub(r"\(.*?\)", "", lab).split()[-1:] or [""]
            if head[0] in known and head[0].upper() not in GENERIC:
                return known[head[0]], lab
            ps = [p for p in C[u]["parents"] if p in C]
            u = ps[0] if ps else None
        return None, None

    add, classes = {}, {}
    for u, c in C.items():
        if c["kind"] != "equipment":
            continue
        k, via = kind(u)
        if not k:
            continue
        classes[c["label"]] = (k, via)
        words = re.sub(r"\(.*?\)", "", c["label"]).replace("-", "").upper().split()
        head = words[-1] if words else ""
        taken = set(R.VOCAB) | set(R.CONSUMER_WORDS) | {w for w, _, _ in R.NOTE_WORDS} | set(R.SYSTEM_TITLE_WORDS)
        if (head.isalpha() and len(head) >= 5 and head not in R.HAND_KIND_OF_NOUN and head not in add
                and head not in taken and head not in GENERIC and k in KEEP_KINDS):
            add[head] = k
    out = ROOT / "descgen" / "vocab_cfihos.py"
    with open(out, "w") as fh:
        fh.write('"""GENERATED by descgen/build_vocab.py from the CFIHOS RDL v2.0 (IOGP JIP36) - do not edit by hand.\n'
                 'KIND_NOUNS: equipment head nouns not already in rules.KIND_OF_NOUN -> descgen kind.\n'
                 'CLASSES: every CFIHOS equipment class with a descgen kind -> (kind, CFIHOS class the kind came from)."""\n\n')
        fh.write("KIND_NOUNS = " + json.dumps(dict(sorted(add.items())), indent=1) + "\n\n")
        fh.write("CLASSES = " + json.dumps(dict(sorted(classes.items())), indent=1) + "\n")
    print(f"{len(classes)} CFIHOS equipment classes mapped to a kind; {len(add)} new kind nouns -> {out}")
    print(sorted(add.items()))


if __name__ == "__main__":
    main()
